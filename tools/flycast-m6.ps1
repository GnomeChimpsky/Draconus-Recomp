# Capture Flycast's own audio for the M6 gate.
#
# Flycast's Windows builds can write their audio output to disk through SDL's "disk" audio
# driver. That gives a digital reference with no loopback device and no system sounds: set
# SDL_AUDIODRIVER=disk and SDL_DISKAUDIOFILE=<raw>, force the sdl2 audio backend, and Flycast
# writes raw s16le stereo 44.1 kHz while it emulates. This script also uses Flycast's Lua
# scripting to press START and A on known guest frames, so the reference reaches the same
# menus/gameplay as the recompiled build.
#
#   tools\flycast-m6.ps1                          # 10 minutes, into work\m6\flycast_10min.wav
#   tools\flycast-m6.ps1 -Seconds 90 -Out work\m6\flycast_90s.wav
#   tools\flycast-m6.ps1 -Frames 36000 -Flycast "D:\flycast\flycast.exe" -Disc "D:\game.gdi"
#
# The capture is guest-time audio, not wall-clock audio: a slow host lengthens the run, it does
# not punch holes in the sound. The default schedule waits 30 s before START because Flycast's
# boot is about three seconds slower than ours, then presses A 5 s later.
param(
    [int]$Seconds = 600,
    [int]$Frames = 0,
    [string]$Out = "",
    [string]$Flycast = "",
    [string]$Disc = "",
    [int]$StartFrame = 1800,
    [int]$AFrame = 2100,
    [int]$HoldFrames = 30,
    [switch]$KeepRaw
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
if ($Frames -le 0) { $Frames = $Seconds * 60 }
if (-not $Out) { $Out = Join-Path $root ("work\m6\flycast_{0}.wav" -f $(if ($Seconds -eq 600) { "10min" } else { "${Seconds}s" })) }
$Out = [IO.Path]::GetFullPath($Out)
New-Item -ItemType Directory -Force (Split-Path -Parent $Out) | Out-Null

if (-not $Flycast) {
    $candidates = @(
        $env:FLYCAST_EXE,
        (Join-Path $root "tools\flycast\flycast.exe"),
        (Get-Command flycast.exe -ErrorAction SilentlyContinue).Source
    ) | Where-Object { $_ }
    $Flycast = $candidates | Where-Object { Test-Path -LiteralPath $_ } | Select-Object -First 1
}
if (-not $Flycast -or -not (Test-Path -LiteralPath $Flycast)) {
    throw "Flycast not found. Pass -Flycast PATH (the executable, not the folder)."
}
$Flycast = (Resolve-Path -LiteralPath $Flycast).Path
$flycastDir = Split-Path -Parent $Flycast

if (-not $Disc) {
    $found = @(Get-ChildItem -LiteralPath $root -Filter '*.gdi' -Recurse -File -ErrorAction SilentlyContinue |
               Where-Object { $_.FullName -notlike "*\work\*" })
    if ($found.Count -eq 0) {
        throw "No .gdi disc found under $root. Pass -Disc PATH to the game's .gdi."
    }
    # The workspace also has the Jan 2000 prototype. Prefer the retail v1.000 dump by name; if
    # that is ambiguous, refuse rather than silently comparing the wrong build's audio.
    $retail = $found | Where-Object { $_.FullName -match '(?i)v1\.000|retail|Crave' } | Select-Object -First 1
    if ($retail) {
        $Disc = $retail.FullName
    } elseif ($found.Count -eq 1) {
        $Disc = $found[0].FullName
    } else {
        $list = ($found | ForEach-Object { "  " + $_.FullName }) -join "`n"
        throw "Several .gdi files found; pass -Disc with the retail one:`n$list"
    }
}
$Disc = (Resolve-Path -LiteralPath $Disc).Path

$raw = [IO.Path]::ChangeExtension($Out, ".raw")
$luaName = "draconus_m6_capture.lua"
$luaPath = Join-Path $flycastDir $luaName
if (Test-Path -LiteralPath $luaPath) { throw "$luaPath already exists; remove it or use a different Flycast copy" }

$lua = @"
-- Generated by tools\flycast-m6.ps1. Guest-frame schedule, then exit.
local frames = 0
local start_frame = $StartFrame
local a_frame = $AFrame
local hold = $HoldFrames
local stop_frame = $Frames
flycast_callbacks = {
    vblank = function()
        frames = frames + 1
        if frames == start_frame then
            flycast.input.pressButtons(1, 8)   -- START
        elseif frames == start_frame + hold then
            flycast.input.releaseButtons(1, 8)
        elseif frames == a_frame then
            flycast.input.pressButtons(1, 4)   -- A
        elseif frames == a_frame + hold then
            flycast.input.releaseButtons(1, 4)
        elseif frames == stop_frame then
            flycast.emulator.exit()
        end
    end
}
"@
Set-Content -LiteralPath $luaPath -Value $lua -Encoding utf8

$oldDriver = $env:SDL_AUDIODRIVER
$oldFile = $env:SDL_DISKAUDIOFILE
if (Test-Path -LiteralPath $raw) { Remove-Item -LiteralPath $raw -Force }
$env:SDL_AUDIODRIVER = "disk"
$env:SDL_DISKAUDIOFILE = $raw

Write-Host ("capturing {0} guest frames ({1:N1} s) from {2}" -f $Frames, ($Frames / 60.0), $Disc)
Write-Host ("Flycast: {0}" -f $Flycast)
try {
    $proc = Start-Process -FilePath $Flycast `
        -ArgumentList @("-config", "audio:backend=sdl2", "-config", "config:LuaFileName=$luaName", "`"$Disc`"") `
        -PassThru
    $limit = [int]($Frames / 60.0 * 3.0 + 120)
    $sw = [Diagnostics.Stopwatch]::StartNew()
    while (-not $proc.HasExited -and $sw.Elapsed.TotalSeconds -lt $limit) {
        Start-Sleep -Milliseconds 500
        $proc.Refresh()
    }
    if (-not $proc.HasExited) {
        Write-Warning "Flycast did not stop after $limit s; killing it. The WAV will be short."
        Stop-Process -Id $proc.Id -Force
        Start-Sleep -Seconds 1
    }
} finally {
    Remove-Item -LiteralPath $luaPath -Force -ErrorAction SilentlyContinue
    $env:SDL_AUDIODRIVER = $oldDriver
    $env:SDL_DISKAUDIOFILE = $oldFile
}

if (-not (Test-Path -LiteralPath $raw)) { throw "Flycast wrote no audio. Is the sdl2 backend present in this build?" }
$rawSeconds = (Get-Item -LiteralPath $raw).Length / 176400.0
Write-Host ("raw audio: {0:N2} s" -f $rawSeconds)
if ($rawSeconds -lt ($Frames / 60.0) * 0.9) {
    Write-Warning ("the capture is shorter than requested ({0:N1} s of {1:N1} s)" -f $rawSeconds, ($Frames / 60.0))
}

& python (Join-Path $root "tools\audio-check.py") raw2wav $raw $Out
if (-not $KeepRaw) { Remove-Item -LiteralPath $raw -Force }
Write-Host ("wrote {0}" -f $Out)
