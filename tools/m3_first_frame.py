"""M3 first-frame comparison: our first non-blank picture against Flycast's.

Our engine boots ``1ST_READ.BIN`` directly, so its first picture is the game's
own first render (the Crave logo fading in). Flycast runs the boot ROM first,
whose Sega licence screen is the first non-black picture but is *not* game
content. Comparing those two pictures would compare different things (the M3
reference doc says so), so this tool finds Flycast's first non-blank **game**
frame and compares that with ours.

Flycast has no screenshot API that is frame-exact, so the capture goes through
the same Lua freeze / ``PrintWindow`` path as the M5 checkpoints
(``tools/m5_flycast_capture.py``). Two passes are needed because the boot ROM
delay is not known in advance:

1. a coarse sweep (default every 30 frames) finds a bright boot-ROM screen and
   then the first frame after it whose picture is non-blank and dark -- the
   game's first picture;
2. a fine sweep over the coarse interval finds that frame exactly.

The pair is judged with the M5 metric: mean absolute RGB difference (MAE,
0-255) at or below the threshold (16 by default), plus a mask-overlap check so
that two almost-black pictures cannot pass merely by both being black. The
measured pair for this title is MAE 0.92 with 0.93 mask overlap.

Usage:
  python tools/m3_first_frame.py --flycast PATH --disc GAME.gdi \\
      --our work/m3/first/our-first.png --frame 103 \\
      --outdir work/m3/first --markerdir work/m3/first/markers

Exit codes: 0 the pair is within tolerance, non-zero otherwise (2 for a bad command line).
"""
import argparse
import os
import shutil
import subprocess
import sys

import numpy as np
from PIL import Image, ImageDraw

TOOLS = os.path.dirname(os.path.abspath(__file__))
CAPTURE = os.path.join(TOOLS, "m5_flycast_capture.py")


def load_image(path):
    image = Image.open(path).convert("RGB")
    return image, np.asarray(image).astype(np.int16)


def bbox(mask):
    ys, xs = np.where(mask)
    if not len(xs):
        return None
    return (int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max()))


def stats(pixels):
    mask = pixels.max(2) > 0
    return {
        "mean": float(pixels.mean()),
        "max": int(pixels.max()),
        "nonblack": int(mask.sum()),
        "mask": mask,
        "bbox": bbox(mask),
    }


def mask_overlap(a, b):
    union = np.logical_or(a, b).sum()
    if not union:
        return 0.0
    return float(np.logical_and(a, b).sum()) / float(union)


def bbox_iou(p, q):
    if p is None or q is None:
        return 0.0
    x0, y0 = max(p[0], q[0]), max(p[1], q[1])
    x1, y1 = min(p[2], q[2]), min(p[3], q[3])
    inter = max(0, x1 - x0 + 1) * max(0, y1 - y0 + 1)
    if not inter:
        return 0.0
    area_p = (p[2] - p[0] + 1) * (p[3] - p[1] + 1)
    area_q = (q[2] - q[0] + 1) * (q[3] - q[1] + 1)
    return float(inter) / float(area_p + area_q - inter)


def write_lua(path, frames, marker_dir):
    """The checkpoint script m5_flycast_capture.py drives: freeze at each frame."""
    marks = marker_dir.replace("\\", "/") + "/"
    stop = max(frames) + 5
    checkpoints = ", ".join(str(f) for f in frames)
    text = f"""-- Generated by tools/m3_first_frame.py. Freeze at each frame until the host
-- has copied the window, then resume; exit after the last frame.
local dir = "{marks}"
local stop_frame = {stop}
local frames = 0
local checkpoints = {{}}
for _, f in ipairs({{{checkpoints}}}) do checkpoints[f] = "f" .. string.format("%04d", f) end
local function exists(p)
    local f = io.open(p, "r")
    if f then f:close() return true end
    return false
end
local function freeze(name)
    local r = io.open(dir .. "ready-" .. name .. ".txt", "w")
    r:write(tostring(frames))
    r:close()
    local go = dir .. "go-" .. name .. ".txt"
    local deadline = os.time() + 60
    while not exists(go) do
        if os.time() > deadline then break end
    end
    os.remove(go)
end
flycast_callbacks = {{
    vblank = function()
        frames = frames + 1
        local name = checkpoints[frames]
        if name then freeze(name) end
        if frames >= stop_frame then flycast.emulator.exit() end
    end
}}
"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def capture(args, frames, outdir, markerdir, tag):
    """Run Flycast once over `frames`, save each frozen client area as PNG."""
    os.makedirs(outdir, exist_ok=True)
    os.makedirs(markerdir, exist_ok=True)
    lua = os.path.join(args.outdir, f"{tag}.lua")
    write_lua(lua, frames, markerdir)
    cmd = [
        sys.executable,
        CAPTURE,
        "--flycast", args.flycast,
        "--disc", args.disc,
        "--lua", lua,
        "--outdir", outdir,
        "--markerdir", markerdir,
        "--width", "960",
        "--height", "720",
        "--timeout", str(args.timeout),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout)
        sys.stderr.write(result.stderr)
        raise SystemExit(f"Flycast capture failed ({tag} pass)")
    missing = [
        f for f in frames
        if not os.path.exists(os.path.join(outdir, f"f{f:04d}.png"))
    ]
    if missing:
        raise SystemExit(f"Flycast captured no picture for frame(s) {missing}")
    pictures = {}
    for f in frames:
        _, pixels = load_image(os.path.join(outdir, f"f{f:04d}.png"))
        pictures[f] = stats(pixels)
    return pictures, outdir


def first_game_frame(args, pictures, frames, after=None):
    """The first non-blank picture after the boot ROM's bright screen.

    `after` is the last frame that belongs to the boot ROM (or None for the
    coarse pass, which does not know it yet). A frame counts as the game's
    first picture when it is past `after`, has visible content and is not the
    bright boot screen. In the coarse pass, frames before a bright screen has
    been seen are ignored, so the boot ROM's own black or dark frames cannot be
    taken for game content.
    """
    seen_bright = after is not None
    for f in frames:
        if after is not None and f <= after:
            continue
        p = pictures[f]
        if p["mean"] > args.bright_mean:
            seen_bright = True
            continue
        if p["nonblack"] >= args.min_pixels and (seen_bright or not args.require_bright):
            return f
    return None


def save_review(args, our_image, their_image, our_frame, their_frame):
    review = os.path.join(args.outdir, "review")
    os.makedirs(review, exist_ok=True)
    sbs = Image.new("RGB", (our_image.width * 2 + 8, our_image.height), (0, 0, 0))
    sbs.paste(our_image, (0, 0))
    sbs.paste(their_image, (our_image.width + 8, 0))
    draw = ImageDraw.Draw(sbs)
    draw.text((4, 4), f"ours guest {our_frame}  |  flycast frame {their_frame}", (255, 255, 0))
    sbs_path = os.path.join(review, "sbs-first-frame.png")
    sbs.save(sbs_path)
    a = np.asarray(our_image).astype(np.int16)
    b = np.asarray(their_image).astype(np.int16)
    heat = np.clip(np.abs(a - b).max(2) * 4, 0, 255).astype(np.uint8)
    diff_path = os.path.join(review, "diff-first-frame.png")
    Image.fromarray(heat).save(diff_path)
    return sbs_path, diff_path


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--flycast", required=True, help="flycast.exe")
    ap.add_argument("--disc", required=True, help="the game's .gdi/.chd")
    ap.add_argument("--our", required=True, help="our first non-blank frame as PNG")
    ap.add_argument("--frame", type=int, required=True,
                    help="our guest frame number (from DREAM_FIRST_FRAME)")
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--markerdir", required=True)
    ap.add_argument("--threshold", type=float, default=16.0,
                    help="MAE limit, the same metric and default as the M5 check")
    ap.add_argument("--min-overlap", type=float, default=0.50,
                    help="minimum overlap of the two non-black pixel masks")
    ap.add_argument("--start", type=int, default=60,
                    help="first frame of the coarse sweep (default 60)")
    ap.add_argument("--stop", type=int, default=900,
                    help="last frame of the coarse sweep (default 900, 15 s)")
    ap.add_argument("--coarse", type=int, default=30,
                    help="coarse sweep step in frames (default 30)")
    ap.add_argument("--bright-mean", type=float, default=60.0,
                    help="a picture this bright is a boot/licence screen (default 60)")
    ap.add_argument("--min-pixels", type=int, default=100,
                    help="non-black pixels needed for a picture to count (default 100)")
    ap.add_argument("--require-bright", action="store_true", default=True,
                    help="require a bright boot screen before game content (default)")
    ap.add_argument("--no-require-bright", dest="require_bright", action="store_false",
                    help="for a Flycast build that shows no boot screen")
    ap.add_argument("--timeout", type=float, default=180.0,
                    help="timeout for one Flycast launch in seconds")
    args = ap.parse_args()

    args.outdir = os.path.abspath(args.outdir)
    args.markerdir = os.path.abspath(args.markerdir)
    os.makedirs(args.outdir, exist_ok=True)
    if not os.path.isfile(args.our):
        raise SystemExit(f"missing our first-frame picture: {args.our}")

    our_image, our_pixels = load_image(args.our)
    our = stats(our_pixels)
    if our["nonblack"] < args.min_pixels:
        raise SystemExit(
            f"our frame {args.frame} is blank ({our['nonblack']} non-black pixels); "
            "DREAM_FIRST_FRAME and the dump disagree"
        )
    if our_image.size != (960, 720):
        raise SystemExit(f"our picture is {our_image.size}, expected 960x720")

    coarse_frames = list(range(args.start, args.stop + 1, args.coarse))
    if not coarse_frames:
        raise SystemExit("empty coarse sweep; check --start/--stop/--coarse")
    coarse_pictures, _ = capture(
        args, coarse_frames, os.path.join(args.outdir, "coarse"),
        os.path.join(args.markerdir, "coarse"), "coarse",
    )
    coarse_game = first_game_frame(args, coarse_pictures, coarse_frames)
    if coarse_game is None:
        raise SystemExit(
            f"no game picture in the coarse sweep {args.start}..{args.stop}; "
            "Flycast may be showing only the boot ROM -- raise --stop, or pass "
            "--no-require-bright if this Flycast shows no boot screen"
        )

    bright_frames = [
        f for f in coarse_frames
        if f <= coarse_game and coarse_pictures[f]["mean"] > args.bright_mean
    ]
    boot_end = max(bright_frames) if bright_frames else None

    fine_start = max(args.start, coarse_game - args.coarse)
    fine_frames = list(range(fine_start, coarse_game + 1))
    fine_pictures, fine_dir = capture(
        args, fine_frames, os.path.join(args.outdir, "fine"),
        os.path.join(args.markerdir, "fine"), "fine",
    )
    game_frame = first_game_frame(args, fine_pictures, fine_frames, boot_end)
    if game_frame is None:
        raise SystemExit("the fine sweep did not find Flycast's first game picture")
    # The last bright frame of the fine sweep is the true end of the boot screen;
    # the coarse pass only knows it to within one coarse step.
    fine_boot_end = max(
        (f for f in fine_frames
         if f < game_frame and fine_pictures[f]["mean"] > args.bright_mean),
        default=boot_end,
    )

    their_image, their_pixels = load_image(os.path.join(fine_dir, f"f{game_frame:04d}.png"))
    if their_image.size != our_image.size:
        raise SystemExit(
            f"picture sizes differ: ours {our_image.size}, Flycast {their_image.size}"
        )
    their = stats(their_pixels)

    a = np.asarray(our_image).astype(np.int16)
    b = np.asarray(their_image).astype(np.int16)
    difference = np.abs(a - b)
    mae = float(difference.mean())
    rmse = float(np.sqrt(((a - b) ** 2).mean()))
    overlap = mask_overlap(our["mask"], their["mask"])
    iou = bbox_iou(our["bbox"], their["bbox"])

    chosen = os.path.join(args.outdir, "flycast-first.png")
    shutil.copyfile(os.path.join(fine_dir, f"f{game_frame:04d}.png"), chosen)
    sbs, _ = save_review(args, our_image, their_image, args.frame, game_frame)

    ok = mae <= args.threshold and overlap >= args.min_overlap
    lines = [
        f"ours:       guest frame {args.frame}, {our['nonblack']} non-black pixels, max {our['max']}",
    ]
    if fine_boot_end is not None:
        lines.append(
            f"flycast:    boot screen ends at frame {fine_boot_end}"
            " (the Sega licence screen is not game content)"
        )
    else:
        lines.append("flycast:    no boot screen seen; the first non-black picture is game content")
    lines += [
        f"flycast:    first game picture at frame {game_frame},"
        f" {their['nonblack']} non-black pixels, max {their['max']}",
        f"pair:       MAE {mae:.2f}, RMSE {rmse:.2f}, mask overlap {overlap:.2f},"
        f" bbox IoU {iou:.2f}",
        f"tolerance:  MAE <= {args.threshold:g}, mask overlap >= {args.min_overlap:g}"
        f" -- {'PASS' if ok else 'FAIL'}",
        f"pictures:   {args.our} vs {chosen}",
        f"review:     {sbs}",
    ]
    for line in lines:
        print(line)
    with open(os.path.join(args.outdir, "summary.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
