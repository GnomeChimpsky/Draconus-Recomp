"""Freeze Flycast at chosen guest frames and save its client area.

The Lua script (generated by m5-check.ps1) writes a ready file at each checkpoint and
spins until this host writes the matching go file, so the emulated frame is held still
while the window is copied. Flycast has no screenshot API, and its F12 screenshot is
asynchronous; this is the frame-exact alternative.

The client area is read with PrintWindow(PW_CLIENTONLY | PW_RENDERFULLCONTENT), which
works even when the window is covered. A screen grab was the first implementation and
was intermittently wrong when another window sat above Flycast, so the frame holds while
PrintWindow copies it.

Usage:
  python tools/m5_flycast_capture.py --flycast PATH --disc GAME.gdi --lua SCRIPT.lua
      --outdir work/m5/flycast --markerdir work/m5/flycast --width 960 --height 720

The Lua file is copied next to flycast.exe because Flycast resolves config:LuaFileName
against its own directory. The original is left alone.
"""
import argparse
import ctypes
import ctypes.wintypes as wt
import os
import shutil
import subprocess
import sys
import time

from PIL import Image

user32 = ctypes.windll.user32
gdi32 = ctypes.windll.gdi32

user32.GetDC.restype = ctypes.c_void_p
user32.GetDC.argtypes = [wt.HWND]
user32.ReleaseDC.argtypes = [wt.HWND, ctypes.c_void_p]
user32.PrintWindow.argtypes = [wt.HWND, ctypes.c_void_p, wt.UINT]
gdi32.CreateCompatibleDC.restype = ctypes.c_void_p
gdi32.CreateCompatibleDC.argtypes = [ctypes.c_void_p]
gdi32.CreateCompatibleBitmap.restype = ctypes.c_void_p
gdi32.CreateCompatibleBitmap.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_int]
gdi32.SelectObject.restype = ctypes.c_void_p
gdi32.SelectObject.argtypes = [ctypes.c_void_p, ctypes.c_void_p]
gdi32.DeleteObject.argtypes = [ctypes.c_void_p]
gdi32.DeleteDC.argtypes = [ctypes.c_void_p]
gdi32.GetDIBits.argtypes = [
    ctypes.c_void_p, ctypes.c_void_p, wt.UINT, wt.UINT, ctypes.c_void_p, ctypes.c_void_p, wt.UINT
]

PW_CLIENTONLY = 0x1
PW_RENDERFULLCONTENT = 0x2

SW_RESTORE = 9
SW_SHOW = 5
SWP_NOSIZE = 0x0001
SWP_NOMOVE = 0x0002
SWP_SHOWWINDOW = 0x0040


def keep_window_awake(hwnd):
    """Flycast stops producing vblanks while minimised, which would freeze the Lua script.

    A shared desktop can minimise or cover the window at any moment, so restore and raise it
    before every capture. PrintWindow reads the client area regardless of what is above it.
    """
    if user32.IsIconic(hwnd):
        user32.ShowWindow(hwnd, SW_RESTORE)
    if not user32.IsWindowVisible(hwnd):
        user32.ShowWindow(hwnd, SW_SHOW)
    user32.SetWindowPos(hwnd, wt.HWND(-1), 0, 0, 0, 0,
                        SWP_NOMOVE | SWP_NOSIZE | SWP_SHOWWINDOW)


class BitmapInfoHeader(ctypes.Structure):
    _fields_ = [
        ("biSize", wt.DWORD),
        ("biWidth", ctypes.c_long),
        ("biHeight", ctypes.c_long),
        ("biPlanes", wt.WORD),
        ("biBitCount", wt.WORD),
        ("biCompression", wt.DWORD),
        ("biSizeImage", wt.DWORD),
        ("biXPelsPerMeter", ctypes.c_long),
        ("biYPelsPerMeter", ctypes.c_long),
        ("biClrUsed", wt.DWORD),
        ("biClrImportant", wt.DWORD),
    ]


def find_window(pid, min_w, min_h, timeout=30.0):
    """The game window: visible, titled Flycast, and at least min_w x min_h."""
    end = time.time() + timeout
    while time.time() < end:
        found = []

        @ctypes.WINFUNCTYPE(wt.BOOL, wt.HWND, wt.LPARAM)
        def enum(hwnd, _):
            p = wt.DWORD()
            user32.GetWindowThreadProcessId(hwnd, ctypes.byref(p))
            if p.value != pid or not user32.IsWindowVisible(hwnd):
                return True
            n = user32.GetWindowTextLengthW(hwnd)
            if n <= 0:
                return True
            buf = ctypes.create_unicode_buffer(n + 1)
            user32.GetWindowTextW(hwnd, buf, n + 1)
            if "Flycast" not in buf.value:
                return True
            rc = wt.RECT()
            user32.GetClientRect(hwnd, ctypes.byref(rc))
            if rc.right - rc.left < min_w or rc.bottom - rc.top < min_h:
                return True
            found.append(hwnd)
            return True

        user32.EnumWindows(enum, 0)
        if found:
            return found[0]
        time.sleep(0.1)
    return None


def capture_client(hwnd):
    """The client area, at its exact size, independent of what covers the window."""
    rc = wt.RECT()
    if not user32.GetClientRect(hwnd, ctypes.byref(rc)):
        raise RuntimeError("GetClientRect failed")
    w, h = rc.right - rc.left, rc.bottom - rc.top
    if w <= 0 or h <= 0:
        raise RuntimeError(f"empty client area {w}x{h}")

    hdc = user32.GetDC(hwnd)
    mem = gdi32.CreateCompatibleDC(hdc)
    bmp = gdi32.CreateCompatibleBitmap(hdc, w, h)
    try:
        gdi32.SelectObject(mem, bmp)
        if not user32.PrintWindow(hwnd, mem, PW_CLIENTONLY | PW_RENDERFULLCONTENT):
            raise RuntimeError("PrintWindow failed")
        bi = BitmapInfoHeader()
        bi.biSize = ctypes.sizeof(BitmapInfoHeader)
        bi.biWidth = w
        bi.biHeight = -h  # top-down
        bi.biPlanes = 1
        bi.biBitCount = 32
        bi.biCompression = 0  # BI_RGB
        buf = ctypes.create_string_buffer(w * h * 4)
        if not gdi32.GetDIBits(mem, bmp, 0, h, buf, ctypes.byref(bi), 0):
            raise RuntimeError("GetDIBits failed")
        img = Image.frombuffer("RGB", (w, h), buf, "raw", "BGRX", 0, 1)
        return img.copy()
    finally:
        gdi32.DeleteObject(bmp)
        gdi32.DeleteDC(mem)
        user32.ReleaseDC(hwnd, hdc)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--flycast", required=True)
    ap.add_argument("--disc", required=True)
    ap.add_argument("--lua", required=True)
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--markerdir", required=True)
    ap.add_argument("--width", type=int, default=960)
    ap.add_argument("--height", type=int, default=720)
    ap.add_argument("--timeout", type=float, default=300.0)
    ap.add_argument("--settle", type=float, default=0.1)
    args = ap.parse_args()

    flycast = os.path.abspath(args.flycast)
    flycast_dir = os.path.dirname(flycast)
    outdir = os.path.abspath(args.outdir)
    marker_dir = os.path.abspath(args.markerdir)
    os.makedirs(outdir, exist_ok=True)
    os.makedirs(marker_dir, exist_ok=True)
    for f in os.listdir(marker_dir):
        if f.startswith(("ready-", "go-")):
            os.remove(os.path.join(marker_dir, f))

    # Flycast resolves config:LuaFileName against its own directory.
    lua_name = os.path.basename(args.lua)
    lua_target = os.path.join(flycast_dir, lua_name)
    copied_lua = os.path.abspath(args.lua) != os.path.abspath(lua_target)
    if copied_lua:
        shutil.copyfile(args.lua, lua_target)

    cmd = [
        flycast,
        "-config", "config:LuaFileName=" + lua_name,
        "-config", "rend.WideScreen=no",
        "-config", "rend.ScreenStretching=100",
        "-config", f"window:width={args.width}",
        "-config", f"window:height={args.height}",
        args.disc,
    ]
    proc = subprocess.Popen(cmd, cwd=flycast_dir)
    try:
        hwnd = find_window(proc.pid, args.width // 2, args.height // 2)
        if not hwnd:
            raise RuntimeError("no Flycast game window appeared")
        time.sleep(0.3)
        keep_window_awake(hwnd)
        img = capture_client(hwnd)
        print(f"window {img.size[0]}x{img.size[1]}", flush=True)

        seen = set()
        start = time.time()
        last_raise = 0.0
        while time.time() - start < args.timeout:
            if proc.poll() is not None:
                print("flycast exited", flush=True)
                break
            now = time.time()
            if now - last_raise > 0.5:
                keep_window_awake(hwnd)
                last_raise = now
            for f in sorted(os.listdir(marker_dir)):
                if not f.startswith("ready-") or not f.endswith(".txt") or f in seen:
                    continue
                seen.add(f)
                name = f[len("ready-"):-4]
                time.sleep(args.settle)
                keep_window_awake(hwnd)
                img = capture_client(hwnd)
                path = os.path.join(outdir, name + ".png")
                img.save(path)
                print(f"captured {name} ({img.size[0]}x{img.size[1]})", flush=True)
                with open(os.path.join(marker_dir, "go-" + name + ".txt"), "w") as go:
                    go.write("go")
            time.sleep(0.005)
    finally:
        if proc.poll() is None:
            time.sleep(0.2)
            proc.terminate()
        if copied_lua:
            try:
                os.remove(lua_target)
            except OSError:
                pass


if __name__ == "__main__":
    main()
